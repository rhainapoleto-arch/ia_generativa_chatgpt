# 1. Atribuição Simples (=)
x = 10
print("Valor inicial de X: ", x)

# 2. Atribuição Reduzida Adição (+=)
x += 5
print("Após x += 5: ", x)

# 3. Atribuição Reduzida Adição (-=)
x -= 3
print("Após x -= 3: ", x)

# 4. Atribuição Reduzida Adição (*=)
x *= 2
print("Após x -= 2: ", x)

# Anotações;
# 5 / 2 = 2.5
# 5 // 2 = 2 (arredonda a conta na casa dos inteiros).
# 4**3 = 16 (exponenciação).
# Regra de Precedência: Define qual a operação para se realizar primeiro.

