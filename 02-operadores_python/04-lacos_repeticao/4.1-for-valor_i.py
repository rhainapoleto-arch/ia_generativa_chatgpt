# FOR - Quando sabemos a quantidade de repetições.
# WHILE - Quando não sabemos a quantidade de vezes.

# Exemplo FOR - A primeira variável sempre começa no ZERO e faz a contagem.
# for i in range (3)... (3 fixo)...
# for i in range (1,4)... (3 com definição)...
# for i in range (2,10,2)... (início, fim, salto)...

for i in range(10):
    print(i)

